import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import zlib from 'node:zlib';
const root=new URL('../../',import.meta.url),context=vm.createContext({window:{},console:{warn(){}}});
for(const name of ['public/shared/vendor/three/three.min.js','public/games/city-flight/scenery/city-styles.js','public/games/city-flight/scenery/daylight.js','public/games/city-flight/scenery/urban-light.js'])vm.runInContext(fs.readFileSync(new URL(name,root),'utf8'),context);
const T=context.THREE,{CityStyles,CityDaylight,CityUrbanLight}=context.window,style=CityStyles.forCity({id:'berlin'}),solar=CityDaylight.solarPosition(style.solar);
assert.equal(style.season,'autumn');
assert(solar.elevation>19&&solar.elevation<21,'October afternoon has a low sun');
assert(solar.azimuth>214&&solar.azimuth<216,'sun is in the southwest');
assert(solar.direction[0]<0&&solar.direction[2]>0,'mapped west is -X and south is +Z');
const at=(date,latitude=52.52,longitude=13.405)=>CityDaylight.solarPosition({date,latitude,longitude});
assert(at('2026-06-21T11:00:00Z').elevation>at('2026-12-21T11:00:00Z').elevation+40,'sun follows the season');
assert(at('2026-03-20T12:00:00Z',0,0).elevation>87,'equinox sun is overhead near the equator at solar noon');
assert(at('2026-03-20T06:30:00Z',0,0).direction[0]>0&&at('2026-03-20T17:30:00Z',0,0).direction[0]<0,'morning east and evening west');
assert.throws(()=>at('invalid'),'invalid date fails rather than creating NaN geometry');
for(const id of ['paris','london','rome','venice','bengaluru','dubai'])assert.equal(CityStyles.forCity({id}).season,null,'autumn stays in Berlin');
const light=CityDaylight.create({T,scene:new T.Scene(),renderer:{shadowMap:{}},style}),texture=light.environmentTexture();
assert.equal(light.sunColor.r,light.sunColor.g,'direct sunlight does not add an amber colour cast');
assert.equal(light.sunColor.g,light.sunColor.b,'direct sunlight keeps neutral whites');
let peak=0,brightness=0;const {data,width,height}=texture.image;
for(let i=0;i<data.length;i+=4){const v=[data[i],data[i+1],data[i+2]].map(T.DataUtils.fromHalfFloat).reduce((a,b)=>a+b,0);assert(Number.isFinite(v));if(v>brightness){brightness=v;peak=i/4;}}
const x=peak%width,y=Math.floor(peak/width),theta=(y+.5)/height*Math.PI,phi=((x+.5)/width-.5)*2*Math.PI;
assert(new T.Vector3(Math.cos(phi)*Math.sin(theta),-Math.cos(theta),Math.sin(phi)*Math.sin(theta)).dot(light.direction)>.9998,'HDR reflected sun agrees with the geographic sun');
assert(brightness>6,'sun keeps HDR brightness');
const settings={size:24,cell:4,origin:[-48,-48]},open=CityUrbanLight.field([],settings);
assert(open.data.every(v=>v===255),'open land receives an unobstructed sky');
const box=(x0,z0,x1,z1)=>({k:'building',h:35,p:[[x0,z0],[x1,z0],[x1,z1],[x0,z1]]});
const enclosed=CityUrbanLight.field([box(-20,-20,-8,20),box(8,-20,20,20),box(-8,-20,8,-8),box(-8,8,8,20)],settings);
const probe=layer=>enclosed.data[((layer*24+12)*24+12)*4]/255;
assert(probe(0)<.55,'enclosed courtyard receives less sky light');
assert(probe(4)>.95&&probe(4)>probe(0),'rooftops above their neighbours stay open to the sky');
const map=JSON.parse(zlib.gunzipSync(fs.readFileSync(new URL('public/games/city-flight/berlin/data/berlin.bin',root))));
const actual=CityUrbanLight.field(map.features);
assert(actual.stats.buildings>500&&actual.stats.minimumVisibility<.6,'real Berlin blocks contribute to the bake');
assert.equal(actual.data.length,96*96*7*4,'fixed-size atlas bounds the GPU cost');
console.log('PASS Berlin autumn: seasonal sun, map orientation, HDR reflections, city isolation and baked sky visibility',actual.stats);
